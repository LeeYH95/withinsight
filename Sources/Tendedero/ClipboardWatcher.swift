import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

/// Reads each new clipboard item once. Decoding and writing stay on a serial
/// worker so successive copies retain their order without blocking the editor.
@MainActor
final class ClipboardWatcher {
    private let board: NSPasteboard
    private let folder: URL
    private let isHanging: (URL) -> Bool
    private let onImages: ([URL]) -> Void
    private let worker = DispatchQueue(label: "Shipian.clipboard-images", qos: .userInitiated)
    private var timer: Timer?
    private var lastCount: Int
    private var generation = UUID()
    private var pendingBytes = 0
    private var recent: [String: URL] = [:]
    private static let enabledKey = "clipboardEnabled"
    private static let maxBytes = 64 * 1024 * 1024
    private static let maxPixels = 80_000_000
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        NotesEditorPasteboard.copiedImageType,
    ]

    private enum Source: Sendable {
        case image(Data)
        case file(URL)
        var cost: Int {
            switch self {
            case .image(let data): return data.count
            case .file: return 1024
            }
        }
    }
    private struct Saved: Sendable {
        let digest: String
        let url: URL
    }

    var isProcessing: Bool { pendingBytes > 0 }

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    init(board: NSPasteboard = .general,
         folder: URL = Inbox.folder.appendingPathComponent("Clipboard", isDirectory: true),
         isHanging: @escaping (URL) -> Bool,
         onImages: @escaping ([URL]) -> Void) {
        self.board = board
        self.folder = folder
        self.isHanging = isHanging
        self.onImages = onImages
        lastCount = board.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastCount = board.changeCount
        generation = UUID()
        let timer = Timer(timeInterval: 0.2, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        generation = UUID()
    }

    func check() {
        guard timer != nil, board.changeCount != lastCount,
              pendingBytes < Self.maxBytes * 2 else { return }
        let count = board.changeCount
        let items = board.pasteboardItems ?? []
        // A sensitive marker on any item protects the entire copy.
        guard items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }) else {
            lastCount = count
            return
        }
        var sources: [Source] = []
        var cost = 0
        for item in items {
            guard let source = Self.source(item) else { continue }
            if case .file(let url) = source, isHanging(url) { continue }
            guard source.cost <= Self.maxBytes * 2 - cost else {
                lastCount = count
                return
            }
            cost += source.cost
            sources.append(source)
        }
        guard board.changeCount == count else { return }
        guard pendingBytes + cost <= Self.maxBytes * 2 else { return }
        lastCount = count
        guard !sources.isEmpty else { return }
        pendingBytes += cost
        let token = generation
        let folder = folder
        worker.async { [weak self] in
            let saved = sources.compactMap { source in
                autoreleasepool { Self.save(source, in: folder) }
            }
            DispatchQueue.main.async { [weak self] in
                guard let self else {
                    Self.remove(saved)
                    return
                }
                self.pendingBytes -= cost
                guard self.timer != nil, self.generation == token else {
                    self.worker.async { Self.remove(saved) }
                    return
                }
                self.recent = self.recent.filter { self.isHanging($0.value) }
                var accepted: [URL] = []
                var duplicates: [Saved] = []
                var batchDigests = Set<String>()
                for image in saved {
                    if !batchDigests.insert(image.digest).inserted
                        || self.recent[image.digest].map(self.isHanging) == true {
                        duplicates.append(image)
                    } else {
                        self.recent[image.digest] = image.url
                        accepted.append(image.url)
                    }
                }
                if !accepted.isEmpty { self.onImages(accepted) }
                self.worker.async { Self.remove(duplicates) }
            }
        }
    }

    private static func source(_ item: NSPasteboardItem) -> Source? {
        if let raw = item.string(forType: .fileURL), let url = URL(string: raw), url.isFileURL {
            return .file(url)
        }
        // Rich document fragments may carry an image representation of text.
        guard !item.types.contains(.rtf), !item.types.contains(.rtfd) else { return nil }
        if let text = item.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           NotesWebLink.url(from: text) == nil { return nil }
        guard let type = item.availableType(from: [.png, .tiff, .init("public.jpeg"), .init("public.heic")]),
              let data = item.data(forType: type), data.count <= maxBytes else { return nil }
        return .image(data)
    }

    nonisolated private static func save(_ source: Source, in folder: URL) -> Saved? {
        let fm = FileManager.default
        let url = folder.appendingPathComponent("Clipboard " + UUID().uuidString + ".png")
        do {
            let data: Data
            switch source {
            case .image(let bytes): data = bytes
            case .file(let file):
                let info = try file.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey, .contentTypeKey])
                guard info.isRegularFile == true, info.isSymbolicLink != true,
                      info.contentType?.conforms(to: .image) == true,
                      let size = info.fileSize, size <= maxBytes else { return nil }
                data = try Data(contentsOf: file, options: .mappedIfSafe)
            }
            guard data.count <= maxBytes, let image = CGImageSourceCreateWithData(data as CFData, nil),
                  let properties = CGImageSourceCopyPropertiesAtIndex(image, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? Int,
                  let height = properties[kCGImagePropertyPixelHeight] as? Int,
                  width > 0, height > 0, width <= maxPixels / height else { return nil }
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: max(width, height),
            ]
            guard let decoded = CGImageSourceCreateThumbnailAtIndex(image, 0, options as CFDictionary),
                  let png = NSBitmapImageRep(cgImage: decoded).representation(using: .png, properties: [:]),
                  png.count <= maxBytes else { return nil }
            try fm.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try png.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return Saved(digest: SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined(), url: url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a copied image: \(error.localizedDescription, privacy: .public)")
            return nil
        }
    }

    nonisolated private static func remove(_ images: [Saved]) {
        for image in images { try? FileManager.default.removeItem(at: image.url) }
    }
}
